#!/usr/bin/env python3
"""Generate Sources/VoiceCloneCore/LegalTexts.swift from the Android LegalTexts.kt, so both apps show the same terms.

  python3 ios/scripts/generate_legal.py            # rewrite the Swift file
  python3 ios/scripts/generate_legal.py --check    # exit 1 when the Swift file is out of date
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "android/app/src/main/java/com/voiceclone/app/LegalTexts.kt"
TARGET = ROOT / "ios/Sources/VoiceCloneCore/LegalTexts.swift"


def kotlin_string(expression: str) -> str:
    """Evaluate `"a\\n" + "b"` (Kotlin string literals joined with +)."""
    pieces = re.findall(r'"((?:[^"\\]|\\.)*)"', expression)
    out = []
    for piece in pieces:
        out.append(re.sub(r"\\(.)", lambda m: {"n": "\n", "t": "\t", '"': '"', "\\": "\\", "$": "$"}.get(m.group(1), m.group(1)), piece))
    return "".join(out)


def swift_literal(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return '"' + escaped + '"'


def generate() -> str:
    source = SOURCE.read_text(encoding="utf-8")
    version = int(re.search(r"const val VERSION = (\d+)", source).group(1))
    values = {}
    for name in ("SUMMARY", "TERMS", "PRIVACY"):
        match = re.search(r"const val %s = (.*?)\n\n|const val %s = (.*?)\n}" % (name, name), source, re.S)
        body = match.group(1) or match.group(2)
        values[name] = kotlin_string(body)
    lines = [
        "// Generated by ios/scripts/generate_legal.py from android/.../LegalTexts.kt. Do not edit by hand.",
        "import Foundation",
        "",
        "/// Terms of use and privacy policy shown inside the app (first launch and Settings).",
        "public enum LegalTexts {",
        f"    public static let version = {version}",
        f"    public static let summary = {swift_literal(values['SUMMARY'])}",
        f"    public static let terms = {swift_literal(values['TERMS'])}",
        f"    public static let privacy = {swift_literal(values['PRIVACY'])}",
        "}",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    text = generate()
    if "--check" in sys.argv:
        sys.exit(0 if TARGET.exists() and TARGET.read_text(encoding="utf-8") == text else 1)
    TARGET.write_text(text, encoding="utf-8")
    print("wrote", TARGET.relative_to(ROOT))
